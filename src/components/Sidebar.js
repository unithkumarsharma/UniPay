export default function Sidebar({ collapsed, onToggle }) {
  const pathname = usePathname();
  const searchParams = useSearchParams();
  const { user, logout, getRoleLabel } = useAuth();

  if (!user) return null;

  const items = menuItems[user.role] || [];
  const currentCategory = searchParams ? searchParams.get('category') : null;
  const currentService = searchParams ? searchParams.get('service') : null;

  return (
    <>
      {/* Mobile overlay */}
      {!collapsed && (
        <div className={styles.overlay} onClick={onToggle} />
      )}

      <aside className={`${styles.sidebar} ${collapsed ? styles.collapsed : ''}`}>
        {/* Logo Header */}
        <div className={styles.logo}>
          <div className={styles.logoIcon}>
            <img src="/logo.png" alt="UniPay" width={34} height={34} />
          </div>
          {!collapsed && (
            <div style={{ display: 'flex', flexDirection: 'column' }}>
              <span className={styles.logoText}>UniPay</span>
              <span className={styles.tagline}>Fintech &amp; Retail Network</span>
            </div>
          )}
        </div>

        {/* Navigation Items */}
        <nav className={styles.nav}>
          {!collapsed && (
            <div style={{ 
              fontSize: '0.65rem', 
              fontWeight: 800, 
              color: 'var(--text-tertiary)', 
              letterSpacing: '0.09em', 
              padding: '12px 14px 6px', 
              textTransform: 'uppercase' 
            }}>
              NAVIGATION &amp; PORTALS
            </div>
          )}

          {items.map((item) => {
            // Get the base dashboard path for the current user role
            const rolePaths = {
              admin: '/admin',
              accountant: '/accountant',
              master_distributor: '/master-distributor',
              distributor: '/distributor',
              retailer: '/retailer',
            };
            const basePath = rolePaths[user.role] || '/';

            const isCategoryMatch = item.path.includes('category=') && currentCategory && item.path.includes(encodeURIComponent(currentCategory));
            const isDashboardMatch = item.path === basePath && !currentCategory && !currentService && pathname === basePath;
            const isExactPathMatch = item.path === pathname;

            const isActive = isCategoryMatch || isDashboardMatch || isExactPathMatch;
            const iconSvg = svgIconMap[item.label] || (
              <svg width="17" height="17" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2">
                <circle cx="12" cy="12" r="10" />
              </svg>
            );

            return (
              <Link
                key={item.path}
                href={item.path}
                className={`${styles.navItem} ${isActive ? styles.active : ''}`}
                title={item.label}
                onClick={() => {
                  if (typeof window !== 'undefined' && window.innerWidth <= 768 && !collapsed) {
                    onToggle();
                  }
                }}
              >
                <span className={styles.navIcon} style={{ background: isActive ? 'var(--primary-light)' : 'var(--bg-secondary)', color: 'var(--primary)' }}>
                  {iconSvg}
                </span>
                {!collapsed && <span className={styles.navLabel}>{item.label}</span>}
              </Link>
            );
          })}
        </nav>

        {/* User Info & Logout Button */}
        {!collapsed && (
          <div className={styles.userSection}>
            <div className={styles.userInfo}>
              <div className={styles.userAvatar}>
                {user.name ? user.name.charAt(0).toUpperCase() : 'U'}
              </div>
              <div className={styles.userDetails}>
                <span className={styles.userName}>{user.name}</span>
                <span className={styles.userRole}>{getRoleLabel(user.role)}</span>
              </div>
            </div>
            <button className={styles.logoutBtn} onClick={logout} title="Sign Out">
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2">
                <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
                <polyline points="16 17 21 12 16 7" />
                <line x1="21" y1="12" x2="9" y2="12" />
              </svg>
            </button>
          </div>
        )}
      </aside>
    </>
  );
}
